let lang = 'en';
const listeners = new Set();

export function getLang() { return lang; }
export function locale() { return lang === 'ar' ? 'ar-u-nu-latn' : 'en'; }
export function isRTL() { return lang === 'ar'; }

export function setLang(l) {
  lang = dict[l] ? l : 'en';
  const root = document.documentElement;
  root.lang = lang;
  root.dir = lang === 'ar' ? 'rtl' : 'ltr';
  try { localStorage.setItem('stratax.lang', lang); } catch (_) { /* storage unavailable */ }
  cache.clear();
  listeners.forEach((fn) => fn(lang));
}
export function onLang(fn) { listeners.add(fn); }

function lookup(l, key) {
  return key.split('.').reduce((o, k) => (o == null ? undefined : o[k]), dict[l]);
}

const cache = new Map();
function fmt(kind, opts) {
  const k = kind + JSON.stringify(opts || {});
  if (!cache.has(k)) {
    const Ctor = { n: Intl.NumberFormat, r: Intl.RelativeTimeFormat, p: Intl.PluralRules, d: Intl.DateTimeFormat }[kind];
    cache.set(k, new Ctor(locale(), opts));
  }
  return cache.get(k);
}

/** Translate `key`; `{name}` placeholders are filled from params. Objects are plural maps keyed by Intl.PluralRules. */
export function t(key, params = {}) {
  let v = lookup(lang, key);
  if (v === undefined) v = lookup('en', key);
  if (v === undefined) return key;
  if (typeof v === 'object') {
    const n = Number(params.count ?? 0);
    v = v[fmt('p').select(n)] ?? v.other;
  }
  // Each substituted value is wrapped in FSI..PDI so sizes, paths and names
  // keep their own direction inside Arabic sentences.
  return v.replace(/\{(\w+)\}/g, (_, p) => {
    const val = p === 'count' && typeof params.count === 'number' ? fmtInt(params.count) : params[p] ?? '';
    return val === '' ? '' : '\u2068' + val + '\u2069';
  });
}

export function fmtInt(n) { return fmt('n', { maximumFractionDigits: 0 }).format(n); }
export function fmtNum(n, d = 1) { return fmt('n', { minimumFractionDigits: d, maximumFractionDigits: d }).format(n); }
export function fmtCompact(n) { return fmt('n', { notation: 'compact', maximumFractionDigits: 1 }).format(n); }
export function fmtPct(x, d = 0) { return fmt('n', { style: 'percent', minimumFractionDigits: d, maximumFractionDigits: d }).format(x); }

const UNITS = ['B', 'KB', 'MB', 'GB', 'TB', 'PB'];
/** Binary sizes with conventional labels (GB = 2^30), matching the backend's own strings. */
export function fmtBytes(b) {
  if (b == null || !isFinite(b)) return '-';
  const neg = b < 0; let v = Math.abs(b); let i = 0;
  while (v >= 1024 && i < UNITS.length - 1) { v /= 1024; i++; }
  const d = i === 0 ? 0 : v >= 100 ? 0 : 1;
  return (neg ? '-' : '') + fmtNum(v, d) + ' ' + UNITS[i];
}

export function fmtAge(unix) {
  if (!unix) return t('common.never');
  const diff = unix - Date.now() / 1000;
  const a = Math.abs(diff);
  const rtf = fmt('r', { numeric: 'auto' });
  if (a < 45) return t('age.just');
  if (a < 3600) return rtf.format(Math.round(diff / 60), 'minute');
  if (a < 86400) return rtf.format(Math.round(diff / 3600), 'hour');
  if (a < 86400 * 45) return rtf.format(Math.round(diff / 86400), 'day');
  if (a < 86400 * 365) return rtf.format(Math.round(diff / (86400 * 30)), 'month');
  return rtf.format(Math.round(diff / (86400 * 365)), 'year');
}

/** Plain duration without "ago", e.g. "23 days" for "idle 23 days". */
export function fmtSpan(secs) {
  const u = secs < 3600 ? ['minute', secs / 60] : secs < 86400 ? ['hour', secs / 3600] : secs < 86400 * 60 ? ['day', secs / 86400] : secs < 86400 * 365 ? ['month', secs / (86400 * 30)] : ['year', secs / (86400 * 365)];
  return fmt('n', { style: 'unit', unit: u[0], unitDisplay: 'long', maximumFractionDigits: 0 }).format(Math.max(1, Math.round(u[1])));
}

export function fmtDur(secs) {
  secs = Math.max(0, Math.round(secs));
  const d = Math.floor(secs / 86400), h = Math.floor((secs % 86400) / 3600), m = Math.floor((secs % 3600) / 60), s = secs % 60;
  const n = (x) => fmtInt(x);
  if (d) return t('dur.dh', { d: n(d), h: n(h) });
  if (h) return t('dur.hm', { h: n(h), m: n(m) });
  if (m) return t('dur.ms', { m: n(m), s: n(s) });
  return t('dur.s', { s: n(s) });
}

export function fmtDate(unix) {
  return fmt('d', { dateStyle: 'medium', timeStyle: 'short' }).format(new Date(unix * 1000));
}

export function initLang() {
  let l = 'en';
  try { l = localStorage.getItem('stratax.lang') || 'en'; } catch (_) { /* ignore */ }
  setLang(l);
}
